/// Specification for a `StellarTestnet` resource.
#[derive(CustomResource, Clone, Debug, Deserialize, Serialize, JsonSchema)]
#[kube(
    group = "stellar.org",
    version = "v1alpha1",
    kind = "StellarTestnet",
    namespaced,
    status = "StellarTestnetStatus",
    shortname = "stnet",
    printcolumn = r#"{"name":"Phase","type":"string","jsonPath":".status.phase"}"#,
    printcolumn = r#"{"name":"RPC URL","type":"string","jsonPath":".status.rpcUrl"}"#,
    printcolumn = r#"{"name":"TTL","type":"integer","jsonPath":".spec.ttlSeconds"}"#,
    printcolumn = r#"{"name":"Age","type":"date","jsonPath":".metadata.creationTimestamp"}"#
)]
#[serde(rename_all = "camelCase")]
pub struct StellarTestnetSpec {
    /// Genesis ledger parameters.
    #[serde(default)]
    pub genesis_config: GenesisConfig,

    /// Named accounts to pre-fund at genesis.
    /// The operator generates key-pairs and stores them in a per-testnet Secret.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub funded_accounts: Vec<FundedAccount>,

    /// Soroban RPC sidecar configuration.
    #[serde(default)]
    pub soroban_rpc: SorobanRpcConfig,

    /// Optional Kubernetes `Ingress` configuration for external RPC access.
    #[serde(default)]
    pub ingress: TestnetIngressConfig,

    /// Container image for Stellar Core standalone.
    /// Defaults to `stellar/stellar-core:latest`.
    #[serde(default = "default_core_image")]
    pub stellar_core_image: String,

    /// CPU and memory resource requests for the Stellar Core pod.
    #[serde(default)]
    pub resources: TestnetResources,

    /// Time-to-live in seconds after which the operator will delete this
    /// `StellarTestnet` automatically.  Set to `0` to disable auto-deletion.
    /// Defaults to `3600` (1 hour).
    #[serde(default = "default_ttl")]
    pub ttl_seconds: u64,

    /// Additional labels applied to all Kubernetes objects owned by this testnet.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub labels: BTreeMap<String, String>,
}

fn default_core_image() -> String {
    "stellar/stellar-core:latest".to_string()
}

fn default_ttl() -> u64 {
    3600
}

// ---------------------------------------------------------------------------
// Status
// ---------------------------------------------------------------------------

/// Phase of a `StellarTestnet` resource.
#[derive(Clone, Debug, Default, Deserialize, Serialize, JsonSchema, PartialEq, Eq)]
#[serde(rename_all = "PascalCase")]
pub enum TestnetPhase {
    /// The operator has accepted the resource and is provisioning it.
    #[default]
    Provisioning,
    /// Stellar Core is running and the Soroban RPC endpoint is reachable.
    Ready,
    /// The testnet has exceeded its TTL and is being torn down.
    Terminating,
    /// Provisioning failed; see `conditions` for details.
    Failed,
}

/// Status sub-resource for a `StellarTestnet`.
#[derive(Clone, Debug, Default, Deserialize, Serialize, JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct StellarTestnetStatus {
    /// High-level lifecycle phase.
    #[serde(default)]
    pub phase: TestnetPhase,

    /// Soroban JSON-RPC endpoint URL, e.g. `http://<service>.<ns>.svc:8000`.
    /// Populated once the pod reaches `Running` and the RPC health-check passes.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub rpc_url: Option<String>,

    /// Stellar Core HTTP management endpoint (internal cluster URL).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub core_url: Option<String>,

    /// SCP network passphrase in use (derived or user-supplied).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub network_passphrase: Option<String>,

    /// Map of `account-name → Stellar public key (G…)` for pre-funded accounts.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub funded_public_keys: BTreeMap<String, String>,

    /// Name of the Kubernetes Secret holding private keys for funded accounts.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub funded_keys_secret: Option<String>,

    /// Human-readable message describing the current operator action.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub message: Option<String>,

    /// Unix timestamp (seconds) when the testnet will expire based on `ttlSeconds`.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub expires_at: Option<i64>,

    /// ISO-8601 timestamp of the last successful reconcile.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub last_reconciled_at: Option<String>,

    /// List of Kubernetes conditions for this testnet.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub conditions: Vec<TestnetCondition>,
}

/// A single condition on a `StellarTestnet` resource.
#[derive(Clone, Debug, Deserialize, Serialize, JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct TestnetCondition {
    /// Condition type (e.g. `Ready`, `CoreRunning`, `RpcReachable`).
    #[serde(rename = "type")]
    pub condition_type: String,

    /// `True`, `False`, or `Unknown`.
    pub status: String,

    /// Machine-readable reason code.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub reason: Option<String>,

    /// Human-readable description.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub message: Option<String>,

    /// ISO-8601 timestamp of the last state transition.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub last_transition_time: Option<String>,
}
