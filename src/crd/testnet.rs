/// Minimal CPU/memory requests for the Stellar Core pod.
#[derive(Clone, Debug, Deserialize, Serialize, JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct TestnetResources {
    /// CPU request/limit string (e.g. `"500m"`).
    #[serde(default = "default_cpu")]
    pub cpu: String,

    /// Memory request/limit string (e.g. `"512Mi"`).
    #[serde(default = "default_memory")]
    pub memory: String,
}

fn default_cpu() -> String {
    "500m".to_string()
}

fn default_memory() -> String {
    "512Mi".to_string()
}

impl Default for TestnetResources {
    fn default() -> Self {
        Self {
            cpu: default_cpu(),
            memory: default_memory(),
        }
    }
}

